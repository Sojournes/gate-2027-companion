// Generate detailed lecture items per subject
function buildLecturesForSubjects(subjects) {
  const allLectures = [];
  for (const sub of subjects) {
    for (let i = 1; i <= sub.totalLectures; i++) {
      const topicIdx = Math.min(
        sub.topics.length - 1,
        Math.floor(((i - 1) / sub.totalLectures) * sub.topics.length)
      );
      const partLabel =
        sub.totalLectures > sub.topics.length
          ? ` (Part ${((i - 1) % 2) + 1})`
          : '';
      allLectures.push({
        id: `${sub.id}-lec-${i}`,
        subjectId: sub.id,
        subjectCode: sub.code,
        subjectName: sub.name,
        lectureNumber: i,
        title: `Lec ${String(i).padStart(2, '0')}: ${sub.topics[topicIdx]}${partLabel}`,
        rawDurationMinutes: Math.round(sub.avgLectureRawHours * 60),
        source: sub.batch2027Available ? 'PW 2027 Batch' : 'PW 2026 YouTube',
        completed: false,
        completedAt: null,
        notes: ''
      });
    }
  }
  return allLectures;
}

